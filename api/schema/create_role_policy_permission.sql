-- Create ROLE_POLICY_PERMISSION table
-- ตารางสำหรับเก็บ mapping ระหว่าง Role Policy กับ System/Permission

CREATE TABLE IAMX.ROLE_POLICY_PERMISSION (
    ROLE_POLICY_PERMISSION_ID VARCHAR2(40) PRIMARY KEY,
    ROLE_POLICY_ID VARCHAR2(40) NOT NULL,
    SYSTEM_ID VARCHAR2(4000),  -- comma-separated: "100,200,300"
    PERMISSION_DATA VARCHAR2(4000),  -- comma-separated: "ADMIN_TIS,ADMIN_BTS"
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY VARCHAR2(4000),
    UPDATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR2(4000),
    DELETED_DATE TIMESTAMP,
    DELETED_BY VARCHAR2(4000)
);

-- Create index on ROLE_POLICY_ID for faster lookups
CREATE INDEX IDX_RPP_ROLE_POLICY_ID ON IAMX.ROLE_POLICY_PERMISSION(ROLE_POLICY_ID);

