-- ============================================================
-- Migration: report mapping (role / user)
-- ============================================================
-- Adds:
--   IAMX.ROLE_REPORT_MAPPING  report granted to a role
--   IAMX.USER_REPORT_MAPPING  report granted directly to a user (override)
--
-- Reports themselves live in Report Studio (separate project, separate
-- PostgreSQL DB) and are read over its REST API — IAMX stores mappings only.
-- The join key is REPORT_CODE — GET /reports/codes returns only
-- {code, name}; there is no report id in the payload. Longest code seen
-- in UAT is 21 chars, e.g. 'BGA_00_RPT01_XLSX'. Codes are stored trimmed.
-- No FK is possible across databases: a mapping whose report disappears
-- upstream simply stops rendering a name in the UI.
--
-- Permission model: single `permission` column holding a JSON array
-- (e.g. '["VIEW","EXPORT"]') — same convention as
-- ROLE_OBJECT_PERMISSION.permission. No per-action boolean columns.
--
-- Type notes:
--   ROLE.ID           is VARCHAR2(36) CUID (migrate_role_id_to_cuid.sql)
--   USER_INFO.USER_ID is VARCHAR2(36) CUID (migrate_user_id_to_cuid.sql)
--
-- ทุก object qualify ด้วย IAMX. — ไม่พึ่ง CURRENT_SCHEMA ของ session ที่รัน
-- ============================================================


-- ============================================================
-- PART 1: ROLE -> REPORT mapping
-- ============================================================

CREATE TABLE IAMX.role_report_mapping (
    id               NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id          VARCHAR2(36)    NOT NULL,
    report_code      VARCHAR2(40)    NOT NULL,
    permission       VARCHAR2(500)   DEFAULT '[]' NOT NULL,
    effective_date   DATE            DEFAULT SYSDATE NOT NULL,
    expire_date      DATE,
    is_active        NUMBER(1)       DEFAULT 1 NOT NULL,
    created_by       VARCHAR2(36),
    updated_by       VARCHAR2(36),
    created_at       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_rrpm_role         FOREIGN KEY (role_id) REFERENCES IAMX.role(id),
    CONSTRAINT uq_rrpm_role_report  UNIQUE (role_id, report_code),
    CONSTRAINT ck_rrpm_active       CHECK (is_active IN (0,1)),
    CONSTRAINT ck_rrpm_expire       CHECK (expire_date IS NULL OR expire_date >= effective_date)
);

CREATE INDEX IAMX.idx_rrpm_report ON IAMX.role_report_mapping(report_code);

COMMENT ON TABLE  IAMX.role_report_mapping             IS 'สิทธิ์รายงาน (Report Studio) ระดับบทบาท';
COMMENT ON COLUMN IAMX.role_report_mapping.report_code IS 'รหัสรายงานจาก GET /reports/codes (trim ช่องว่างแล้ว) — ไม่มี FK เพราะอยู่คนละฐานข้อมูล';
COMMENT ON COLUMN IAMX.role_report_mapping.permission  IS 'JSON array of permission codes, e.g. ["VIEW","EXPORT"]';


-- ============================================================
-- PART 2: USER -> REPORT mapping (direct grant / override)
-- ============================================================

CREATE TABLE IAMX.user_report_mapping (
    id               NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          VARCHAR2(36)    NOT NULL,
    report_code      VARCHAR2(40)    NOT NULL,
    permission       VARCHAR2(500)   DEFAULT '[]' NOT NULL,
    override_reason  VARCHAR2(500),
    effective_date   DATE            DEFAULT SYSDATE NOT NULL,
    expire_date      DATE,
    is_active        NUMBER(1)       DEFAULT 1 NOT NULL,
    created_by       VARCHAR2(36),
    updated_by       VARCHAR2(36),
    created_at       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_urpm_user         FOREIGN KEY (user_id) REFERENCES IAMX.user_info(user_id),
    CONSTRAINT uq_urpm_user_report  UNIQUE (user_id, report_code),
    CONSTRAINT ck_urpm_active       CHECK (is_active IN (0,1)),
    CONSTRAINT ck_urpm_expire       CHECK (expire_date IS NULL OR expire_date >= effective_date)
);

CREATE INDEX IAMX.idx_urpm_report ON IAMX.user_report_mapping(report_code);

COMMENT ON TABLE  IAMX.user_report_mapping             IS 'สิทธิ์รายงาน (Report Studio) เฉพาะรายบุคคล';
COMMENT ON COLUMN IAMX.user_report_mapping.report_code IS 'รหัสรายงานจาก GET /reports/codes (trim ช่องว่างแล้ว) — ไม่มี FK เพราะอยู่คนละฐานข้อมูล';
COMMENT ON COLUMN IAMX.user_report_mapping.permission  IS 'JSON array of permission codes, e.g. ["VIEW","EXPORT"]';


-- ============================================================
-- PART 3: seed report permission types
-- Report actions reuse PERMISSION_TYPE so the UI matrix can be
-- driven from the DB instead of a hard-coded list.
-- ============================================================

INSERT INTO IAMX.permission_type (permission_type, permission_type_group, description, is_active)
SELECT 'VIEW', 'REPORT', 'เปิดดูรายงาน', 1 FROM dual
WHERE NOT EXISTS (
    SELECT 1 FROM IAMX.permission_type
    WHERE permission_type = 'VIEW' AND permission_type_group = 'REPORT');

INSERT INTO IAMX.permission_type (permission_type, permission_type_group, description, is_active)
SELECT 'EXPORT', 'REPORT', 'ดาวน์โหลด/ส่งออกไฟล์รายงาน', 1 FROM dual
WHERE NOT EXISTS (
    SELECT 1 FROM IAMX.permission_type
    WHERE permission_type = 'EXPORT' AND permission_type_group = 'REPORT');

INSERT INTO IAMX.permission_type (permission_type, permission_type_group, description, is_active)
SELECT 'PRINT', 'REPORT', 'สั่งพิมพ์รายงาน', 1 FROM dual
WHERE NOT EXISTS (
    SELECT 1 FROM IAMX.permission_type
    WHERE permission_type = 'PRINT' AND permission_type_group = 'REPORT');

COMMIT;
