-- ลบผู้ใช้จาก IAM-X: ฝั่ง IAMX ลบในตัว handler · ฝั่ง APP (คำร้อง UPM ที่ยังไม่อนุมัติ/อนุมัติแล้ว, PDPA, บัญชี UPM)
-- ทำผ่านโพรซีเดอร์นี้ (IAMX มีแค่ SELECT บน APP) · ไม่แตะ APP.M_EMPLOYEE (ทะเบียนบุคลากรจากไฟล์นำเข้า)
-- APP.USER_INFO เป็น VIEW ของ IAMX.USER_INFO (แถวเดียวกัน) → ที่นี่ไม่ลบ user_info (handler ลบเอง) · ใช้ USER_INFO_ID เป็นกุญแจ
CREATE OR REPLACE PROCEDURE APP.PURGE_USER_REQUESTS (p_user_info_id IN VARCHAR2, p_ref_user_id IN VARCHAR2, p_deleted OUT NUMBER) AS
  n NUMBER := 0;
BEGIN
  p_deleted := 0;
  IF p_user_info_id IS NULL THEN RETURN; END IF;
  FOR u IN (SELECT p_user_info_id AS USER_INFO_ID FROM DUAL) LOOP
    -- คำร้องของคนนี้ (ทุกสถานะ) + ลูกของแต่ละแถว
    FOR r IN (SELECT USER_REQ_ID, USER_REQ_FORM_ID FROM APP.USER_REQUESTED WHERE USER_INFO_ID = u.USER_INFO_ID) LOOP
      DELETE FROM APP.USER_REQUESTED_ROLE   WHERE USER_REQ_ID = r.USER_REQ_ID;
      DELETE FROM APP.USER_REQUESTED_OUTPUT WHERE USER_REQ_ID = r.USER_REQ_ID;
      DELETE FROM APP.USER_REQUESTED_LOG    WHERE USER_REQ_ID = r.USER_REQ_ID;
      DELETE FROM APP.USER_INFO_ROLE        WHERE USER_REQ_ID = r.USER_REQ_ID;
      DELETE FROM APP.USER_REQUESTED        WHERE USER_REQ_ID = r.USER_REQ_ID;
      n := n + 1;
      -- ใบคำร้องที่ไม่เหลือแถวของใครแล้ว ลบทั้งใบ
      DELETE FROM APP.USER_REQUESTED_FORM_LOG WHERE USER_REQ_FORM_ID = r.USER_REQ_FORM_ID
        AND NOT EXISTS (SELECT 1 FROM APP.USER_REQUESTED x WHERE x.USER_REQ_FORM_ID = r.USER_REQ_FORM_ID);
      DELETE FROM APP.USER_REQUESTED_FORM WHERE USER_REQ_FORM_ID = r.USER_REQ_FORM_ID
        AND NOT EXISTS (SELECT 1 FROM APP.USER_REQUESTED x WHERE x.USER_REQ_FORM_ID = r.USER_REQ_FORM_ID);
    END LOOP;
    DELETE FROM APP.USER_INFO_ROLE          WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.M_PDPA_AGREE_LOG        WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.M_PDPA_AGREE            WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.USER_AGENCY_VIEW        WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.USER_PERMISSION_SPECIAL WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.USER_REGISTER           WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.USER_REVIEW             WHERE USER_INFO_ID = u.USER_INFO_ID;
    DELETE FROM APP.CANCEL_LICENSE          WHERE USER_INFO_ID = u.USER_INFO_ID;
  END LOOP;
  IF p_ref_user_id IS NOT NULL THEN DELETE FROM APP.EMPLOYEE_AGC_MAP WHERE REF_USER_ID = p_ref_user_id; END IF;
  p_deleted := n;
END;
/
GRANT EXECUTE ON APP.PURGE_USER_REQUESTS TO IAMX
/
-- IAMX มีตาราง APP (ระบบงาน) ทำให้ APP.PURGE_USER_REQUESTS ถูกอ่านเป็นคอลัมน์ของตารางนั้น (PLS-00302) → เรียกผ่าน synonym
CREATE OR REPLACE SYNONYM IAMX.APP_PURGE_USER_REQUESTS FOR APP.PURGE_USER_REQUESTS
/
