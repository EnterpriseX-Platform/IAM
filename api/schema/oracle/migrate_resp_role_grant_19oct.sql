-- ใส่คนเข้าชุด → สร้าง USER_ROLE_MAPPING ตาม role ในชุด (token/view อ่านตารางเดิม ไม่แตะ public API)
-- ตารางนี้จำว่าแถว USER_ROLE_MAPPING ไหนชุดสร้าง → ถอดคนออกจะลบเฉพาะแถวนั้น ไม่ลบ role ที่ให้เองแยก
CREATE TABLE IAMX.RESPONSIBILITY_ROLE_GRANT (
  ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RESPONSIBILITY_ID    NUMBER        NOT NULL,
  USER_ID              VARCHAR2(36 CHAR) NOT NULL,
  ROLE_ID              VARCHAR2(36 CHAR) NOT NULL,
  USER_ROLE_MAPPING_ID NUMBER        NOT NULL,
  CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX IAMX.IX_RRG_RESP_USER ON IAMX.RESPONSIBILITY_ROLE_GRANT (RESPONSIBILITY_ID, USER_ID)
/
CREATE UNIQUE INDEX IAMX.UX_RRG_URM ON IAMX.RESPONSIBILITY_ROLE_GRANT (USER_ROLE_MAPPING_ID)
/
