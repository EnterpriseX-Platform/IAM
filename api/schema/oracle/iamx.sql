-- PROCESS_MAPPER â€” maps ERP Oracle process (N_REF_PROCESS) â†’ IAMX module/object
-- process_id / subprocess_id are uuid strings from ERP master, not local FKs.
CREATE TABLE process_mapper (
    id                NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id         NUMBER,
    object_id         NUMBER,
    fiscal_year       NUMBER(4)       NOT NULL,
    process_id        VARCHAR2(100),                  -- ERP process uuid
    subprocess_id     VARCHAR2(100),                  -- ERP subprocess uuid
    process_name      VARCHAR2(2000)  NOT NULL,
    subprocess_name   VARCHAR2(2000)  NOT NULL,
    display_component VARCHAR2(200)   NOT NULL,
    process_code      VARCHAR2(50)    NOT NULL,
    subprocess_code   VARCHAR2(50)    NOT NULL,
    display_text      VARCHAR2(500)   NOT NULL,
    url               VARCHAR2(1000)  NOT NULL,
    created_at        TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_processmapper_module  FOREIGN KEY (module_id) REFERENCES module(id) ON DELETE CASCADE,
    CONSTRAINT fk_processmapper_object  FOREIGN KEY (object_id) REFERENCES object(id) ON DELETE CASCADE
);

-- PG used a function-based UNIQUE INDEX with COALESCE to treat NULL as
-- 0 in the unique key. Oracle equivalent: NVL inside a UNIQUE index.
CREATE UNIQUE INDEX uq_process_mapper ON process_mapper (
    fiscal_year, process_code, subprocess_code, NVL(module_id, 0), NVL(object_id, 0)
);

-- PROCESS_MAPPER_ROLE — restricts a mapped process to specific roles.
-- No rows for a process_mapper_id = visible to everyone (default).
-- role_id is VARCHAR2(36) CUID (see migrate_role_id_to_cuid.sql), not NUMBER.
CREATE TABLE process_mapper_role (
    process_mapper_id NUMBER        NOT NULL,
    role_id           VARCHAR2(36)  NOT NULL,
    created_at        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_process_mapper_role PRIMARY KEY (process_mapper_id, role_id),
    CONSTRAINT fk_pmr_mapper FOREIGN KEY (process_mapper_id) REFERENCES process_mapper(id) ON DELETE CASCADE,
    CONSTRAINT fk_pmr_role   FOREIGN KEY (role_id) REFERENCES role(id)
);

-- Aggregates allowed_role_ids as a comma-separated list so Go can filter
-- with a simple set-intersection instead of dynamic Oracle IN-list binds.
CREATE OR REPLACE VIEW V_PROCESS_MAPPER_ROLES AS
SELECT
    pm.id, pm.module_id, pm.object_id, pm.fiscal_year,
    pm.process_id, pm.subprocess_id, pm.process_code, pm.subprocess_code,
    pm.process_name, pm.subprocess_name, pm.display_component, pm.display_text, pm.url,
    pm.created_at, pm.updated_at,
    LISTAGG(pmr.role_id, ',') WITHIN GROUP (ORDER BY pmr.role_id) AS allowed_role_ids
FROM process_mapper pm
LEFT JOIN process_mapper_role pmr ON pmr.process_mapper_id = pm.id
GROUP BY pm.id, pm.module_id, pm.object_id, pm.fiscal_year,
    pm.process_id, pm.subprocess_id, pm.process_code, pm.subprocess_code,
    pm.process_name, pm.subprocess_name, pm.display_component, pm.display_text, pm.url,
    pm.created_at, pm.updated_at;


