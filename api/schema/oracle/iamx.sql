-- ============================================================
-- 10. EFFECTIVE PERMISSION VIEW
--     Returns one row per (user_id, object_id, role_id).
--     Priority: 1=Custom > 3=Role. Responsibility removed.
--     Each row carries role's data access as JSON.
-- ============================================================
-- IAMX.V_USER_EFFECTIVE_PERMISSION source

CREATE OR REPLACE VIEW IAMX.V_USER_EFFECTIVE_PERMISSION
(USER_ID,USER_NAME,OBJECT_ID,OBJECT_CODE,OBJECT_ICON,OBJECT_TYPE_CODE,MODULE_ID,MODULE_CODE,MODULE_ICON,MODULE_SORT_ORDER,APPLICATION_ID,APPLICATION_CODE,APPLICATION_ICON,DOMAIN_ID,DOMAIN_CODE,PERMISSION,PERMISSION_LEVEL,SCOPE_FILTER,PERMISSION_SOURCE,PRIORITY,ROLE_ID,ROLE_CODE,ALL_DATA_ACCESS,DEFAULT_AGENCY_PATH,EXTRA_DA_JSON)
AS
SELECT * FROM (
SELECT
    ui.user_id,
    ui.user_name,
    obj.id           AS object_id,
    obj.code         AS object_code,
    CAST(NULL AS VARCHAR2(100)) AS object_icon,
    ot.code          AS object_type_code,
    mod.id           AS module_id,
    mod.code         AS module_code,
    mod.icon         AS module_icon,
    mod.sort_order   AS module_sort_order,
    app.id           AS application_id,
    app.code         AS application_code,
    app.icon         AS application_icon,
    dom.id           AS domain_id,
    dom.code         AS domain_code,
    rop.permission,
    rop.permission_level,
    rop.scope_filter,
    'ROLE'                      AS permission_source,
    3                           AS priority,
    r.id                        AS role_id,
    r.code                      AS role_code,
    r.all_data_access,
    CASE
        WHEN agm.AGC_CODE IS NOT NULL AND aga.AGC_CODE IS NOT NULL AND agd.AGC_CODE IS NOT NULL
            THEN agm.AGC_CODE || '.' || aga.AGC_CODE || '.' || agd.AGC_CODE
        WHEN agm.AGC_CODE IS NOT NULL AND aga.AGC_CODE IS NOT NULL
            THEN agm.AGC_CODE || '.' || aga.AGC_CODE
        WHEN agm.AGC_CODE IS NOT NULL
            THEN agm.AGC_CODE
        ELSE NULL
    END AS default_agency_path,
    COALESCE(
        (SELECT JSON_ARRAYAGG(
            JSON_OBJECT(
                KEY 'agency_path' VALUE ucda.agency_path
            )
         )
         FROM user_custom_data_access ucda
         WHERE ucda.user_id = ui.user_id
           AND (ucda.role_id = r.id OR ucda.role_id IS NULL)
           AND NVL(ucda.type, 'AGENCY') = 'AGENCY'
           AND ucda.is_active = 1
           AND SYSDATE BETWEEN ucda.effective_date AND NVL(ucda.expire_date, SYSDATE)
        ), '[]'
    ) AS extra_da_json
FROM user_info                  ui
JOIN user_role_mapping          url  ON url.user_id = ui.user_id AND url.is_active = 1
JOIN role                       r    ON r.id = url.role_id       AND r.is_active   = 1
JOIN role_object_mapping        rom  ON rom.role_id = r.id       AND rom.is_active = 1
JOIN role_object_permission     rop  ON rop.role_object_mapping_id = rom.id
JOIN object                     obj  ON obj.id = rom.object_id       AND obj.is_active = 1
JOIN object_type                ot   ON ot.id = obj.object_type_id
JOIN module                     mod  ON mod.id = obj.module_id        AND mod.is_active = 1
JOIN application                app  ON app.id = mod.application_id    AND app.is_active = 1
JOIN domain                     dom  ON dom.id = app.domain_id        AND dom.is_active = 1
LEFT JOIN APP.M_AGC             agm  ON agm.AGC_ID = ui.user_ministry_id
LEFT JOIN APP.M_AGC             aga  ON aga.AGC_ID = ui.user_agency_id
LEFT JOIN APP.M_AGC             agd  ON agd.AGC_ID = ui.user_department_id
WHERE SYSDATE BETWEEN url.effective_date AND NVL(url.expire_date, SYSDATE)

UNION ALL

-- Priority 1: User Custom Override (highest)
SELECT
    ui.user_id,
    ui.user_name,
    obj.id           AS object_id,
    obj.code         AS object_code,
    CAST(NULL AS VARCHAR2(100)) AS object_icon,
    ot.code          AS object_type_code,
    mod.id           AS module_id,
    mod.code         AS module_code,
    mod.icon         AS module_icon,
    mod.sort_order   AS module_sort_order,
    app.id           AS application_id,
    app.code         AS application_code,
    app.icon         AS application_icon,
    dom.id           AS domain_id,
    dom.code         AS domain_code,
    ucop.permission,
    ucop.permission_level,
    ucop.scope_filter,
    'CUSTOM'                    AS permission_source,
    1                           AS priority,
    CAST(NULL AS VARCHAR2(36)) AS role_id,
    CAST(NULL AS VARCHAR2(50))  AS role_code,
    0                           AS all_data_access,
    CASE
        WHEN agm.AGC_CODE IS NOT NULL AND aga.AGC_CODE IS NOT NULL AND agd.AGC_CODE IS NOT NULL
            THEN agm.AGC_CODE || '.' || aga.AGC_CODE || '.' || agd.AGC_CODE
        WHEN agm.AGC_CODE IS NOT NULL AND aga.AGC_CODE IS NOT NULL
            THEN agm.AGC_CODE || '.' || aga.AGC_CODE
        WHEN agm.AGC_CODE IS NOT NULL
            THEN agm.AGC_CODE
        ELSE NULL
    END AS default_agency_path,
    COALESCE(
        (SELECT JSON_ARRAYAGG(
            JSON_OBJECT(
                KEY 'agency_path' VALUE ucda.agency_path
            )
         )
         FROM user_custom_data_access ucda
         WHERE ucda.user_id = ui.user_id
           AND ucda.role_id IS NULL
           AND NVL(ucda.type, 'AGENCY') = 'AGENCY'
           AND ucda.is_active = 1
           AND SYSDATE BETWEEN ucda.effective_date AND NVL(ucda.expire_date, SYSDATE)
        ), '[]'
    ) AS extra_da_json
FROM user_info                       ui
JOIN user_custom_object_mapping      ucom ON ucom.user_id = ui.user_id AND ucom.is_active = 1
JOIN user_custom_object_permission   ucop ON ucop.user_custom_object_mapping_id = ucom.id
JOIN object                          obj  ON obj.id = ucom.object_id       AND obj.is_active = 1
JOIN object_type                     ot   ON ot.id = obj.object_type_id
JOIN module                          mod  ON mod.id = obj.module_id         AND mod.is_active = 1
JOIN application                     app  ON app.id = mod.application_id     AND app.is_active = 1
JOIN domain                          dom  ON dom.id = app.domain_id         AND dom.is_active = 1
LEFT JOIN APP.M_AGC                  agm  ON agm.AGC_ID = ui.user_ministry_id
LEFT JOIN APP.M_AGC                  aga  ON aga.AGC_ID = ui.user_agency_id
LEFT JOIN APP.M_AGC                  agd  ON agd.AGC_ID = ui.user_department_id
WHERE SYSDATE BETWEEN ucom.effective_date AND NVL(ucom.expire_date, SYSDATE)
)
WHERE PERMISSION IS NOT NULL AND PERMISSION != '[]';


-- ============================================================
-- 11. EFFECTIVE DATA ACCESS VIEW
--     Returns all (user_id, agency_id) pairs that user has data
--     access to, EXPANDED to include descendants of each scope
--     root via CONNECT BY on APP.M_AGC.
--     Priority: 1=User Custom > 2=Responsibility
-- ============================================================

CREATE OR REPLACE VIEW v_user_effective_data_access AS

-- Priority 2: Through Responsibility
SELECT
    ui.user_id,
    ui.user_name,
    descendant.AGC_ID        AS agency_id,
    descendant.AGC_CODE      AS agency_code,
    descendant.AGC_NAME      AS agency_name,
    rda.agency_id            AS scope_root_agency_id,
    rdap.can_view,
    rdap.can_export,
    rdap.can_share,
    rdap.can_print,
    rda.scope_filter         AS scope_filter,
    'RESPONSIBILITY'         AS permission_source,
    2                        AS priority
FROM user_info                              ui
JOIN user_responsibility_mapping            urm  ON urm.user_id = ui.user_id AND urm.is_active = 1
JOIN responsibility                         resp ON resp.id = urm.responsibility_id AND resp.is_active = 1
JOIN responsibility_data_access             rda  ON rda.responsibility_id = resp.id AND rda.is_active = 1
JOIN responsibility_data_access_permission  rdap ON rdap.responsibility_data_access_id = rda.id
JOIN APP.M_AGC                              descendant
       ON descendant.AGC_ID IN (
           SELECT m.AGC_ID FROM APP.M_AGC m
           START WITH m.AGC_ID = rda.agency_id
           CONNECT BY PRIOR m.AGC_ID = m.PARENT_ID
       )
WHERE SYSDATE BETWEEN urm.effective_date AND NVL(urm.expire_date, SYSDATE)
  AND SYSDATE BETWEEN rda.effective_date AND NVL(rda.expire_date, SYSDATE)

UNION ALL

-- Priority 1: User Custom Data Access (highest)
SELECT
    ui.user_id,
    ui.user_name,
    descendant.AGC_ID        AS agency_id,
    descendant.AGC_CODE      AS agency_code,
    descendant.AGC_NAME      AS agency_name,
    ucda.agency_id           AS scope_root_agency_id,
    ucdap.can_view,
    ucdap.can_export,
    ucdap.can_share,
    ucdap.can_print,
    ucda.scope_filter        AS scope_filter,
    'CUSTOM'                 AS permission_source,
    1                        AS priority
FROM user_info                              ui
JOIN user_custom_data_access                ucda  ON ucda.user_id = ui.user_id AND ucda.is_active = 1 AND NVL(ucda.type, 'AGENCY') = 'AGENCY'
JOIN user_custom_data_access_permission     ucdap ON ucdap.user_custom_data_access_id = ucda.id
JOIN APP.M_AGC                              descendant
       ON descendant.AGC_ID IN (
           SELECT m.AGC_ID FROM APP.M_AGC m
           START WITH m.AGC_ID = ucda.agency_id
           CONNECT BY PRIOR m.AGC_ID = m.PARENT_ID
       )
WHERE SYSDATE BETWEEN ucda.effective_date AND NVL(ucda.expire_date, SYSDATE);


