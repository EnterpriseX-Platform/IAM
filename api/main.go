// @description     The API surface is organized by audience:
// @description       /iamx/api/admin/*  — admin SPA (Keycloak admin role or internal JWT)
// @description       /iamx/api/me/*     — user portal (Keycloak bearer; data of the caller)
// @description       /iamx/api/system/* — ops & webhooks (IP allowlist or service token)
