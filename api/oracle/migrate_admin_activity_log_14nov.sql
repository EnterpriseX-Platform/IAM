-- เขียนโดย middleware ของ API (ทุกคำขอที่แก้ข้อมูล) · อ่านโดยหน้า Activity · ไม่แตะ trigger เดิมของ PERMISSION_AUDIT_LOG
CREATE TABLE IAMX.ADMIN_ACTIVITY_LOG (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ACTOR       VARCHAR2(150 CHAR),
  ACTION      VARCHAR2(20 CHAR)   NOT NULL,   -- POST/PUT/PATCH/DELETE · LOGIN · LOGIN_FAILED
  PATH        VARCHAR2(400 CHAR),
  STATUS      NUMBER(3),
  SUMMARY     VARCHAR2(2000 CHAR),            -- body ย่อ (ตัดรหัสผ่าน/ความลับออก)
  IP_ADDRESS  VARCHAR2(64 CHAR),
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IAMX.IX_AAL_CREATED ON IAMX.ADMIN_ACTIVITY_LOG (CREATED_AT);
CREATE INDEX IAMX.IX_AAL_ACTOR   ON IAMX.ADMIN_ACTIVITY_LOG (ACTOR, CREATED_AT);
