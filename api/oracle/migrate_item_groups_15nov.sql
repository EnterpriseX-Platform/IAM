-- เพิ่มอย่างเดียว: ตารางใหม่ + คอลัมน์ใหม่ที่ว่างได้ · แล้วเติมกลุ่มให้ข้อมูลเดิมตามกติกาเดิมครั้งเดียว
CREATE TABLE IAMX.ITEM_GROUP (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  KIND        VARCHAR2(20 CHAR)  NOT NULL,      -- ROLE | RESP
  CODE        VARCHAR2(40 CHAR)  NOT NULL,
  NAME        VARCHAR2(200 CHAR) NOT NULL,
  SORT_ORDER  NUMBER(5) DEFAULT 0 NOT NULL,
  IS_ACTIVE   NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT UQ_ITEM_GROUP UNIQUE (KIND, CODE)
);
ALTER TABLE IAMX.ROLE ADD (GROUP_CODE VARCHAR2(40 CHAR));
ALTER TABLE IAMX.RESPONSIBILITY ADD (GROUP_CODE VARCHAR2(40 CHAR));

