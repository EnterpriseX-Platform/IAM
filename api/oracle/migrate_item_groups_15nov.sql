-- เติมกลุ่มบทบาทตามกติกาเดิม (roleGroups.ts) · ที่ไม่เข้ากติกา = ไม่มีกลุ่ม (แสดงใน "Ungrouped")
UPDATE IAMX.ROLE SET GROUP_CODE = CASE
  WHEN REGEXP_LIKE(UPPER(CODE), '^(ADMIN|ADMINS|IT-|SUPPORT|HR-|DPO|PDPA)') THEN 'ADMIN'
  WHEN UPPER(CODE) LIKE 'LOAN%' THEN 'LOAN'
  WHEN UPPER(CODE) LIKE 'BUD%' THEN 'BUD'
  WHEN REGEXP_LIKE(UPPER(CODE), '^(STD|EVA)') THEN 'STD'
  WHEN LOWER(ROLE_TYPE) = 'agency' THEN 'AGENCY'
  ELSE NULL END
 WHERE GROUP_CODE IS NULL;
-- เติมกลุ่มความรับผิดชอบตามประเภทผู้สมัคร (เฉพาะชุดบนสุด · ชุดย่อยตามชุดแม่ในหน้าจอ)
UPDATE IAMX.RESPONSIBILITY SET GROUP_CODE = APPLICANT_TYPE
 WHERE GROUP_CODE IS NULL AND APPLICANT_TYPE IN ('INTERNAL','EXTERNAL','BOTH');
COMMIT;
